from pydantic import BaseModel, Field
from typing import List, Optional

class MessageHistory(BaseModel):
    role: str = Field(..., description="Role of the sender: 'user' or 'assistant'")
    content: str = Field(..., description="Content of the message")

class ChatRequest(BaseModel):
    query: str = Field(..., min_length=1, description="User's query/question")
    model: Optional[str] = Field(None, description="Groq model name to use")
    history: Optional[List[MessageHistory]] = Field(default=[], description="Chat history for conversational context")
    conversationId: Optional[str] = Field(None, alias="conversationId", description="Existing conversation ID if continuing thread")
    webSearch: Optional[bool] = Field(True, alias="webSearch", description="Whether to perform web search RAG")

    class Config:
        populate_by_name = True

class Source(BaseModel):
    id: int
    title: str
    url: str
    description: str
    favicon: str

class RelatedQuestion(BaseModel):
    id: int
    text: str

class ChatResponse(BaseModel):
    answer: str = Field(..., description="The answer generated by Groq LLM")
    sources: List[Source] = Field(default=[], description="Sources cited in the answer")
    relatedQuestions: List[RelatedQuestion] = Field(default=[], alias="relatedQuestions", description="Follow-up questions related to the query")
    thinking: List[str] = Field(default=[], description="Simulated/actual engine thinking steps")
    conversationId: str = Field(..., alias="conversationId", description="ID of the conversation thread")
    title: str = Field(..., description="Title of the conversation thread")

    class Config:
        populate_by_name = True

class Message(BaseModel):
    id: str
    role: str
    content: str
    sources: Optional[List[Source]] = None
    relatedQuestions: Optional[List[RelatedQuestion]] = Field(None, alias="relatedQuestions")
    thinking: Optional[List[str]] = None
    timestamp: str

    class Config:
        populate_by_name = True

class Conversation(BaseModel):
    id: str
    title: str
    timestamp: str
    messages: List[Message]
